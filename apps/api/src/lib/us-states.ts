const CODE_SET = new Set(Object.values(US_STATE_NAME_TO_CODE))
const LOWER_NAME_TO_CODE = new Map(
  Object.entries(US_STATE_NAME_TO_CODE).map(
    ([name, code]) => [name.toLowerCase(), code] as const,
  ),
)

export function usStateCodeFromNameOrCode(raw: string): string {
  const trimmed = raw.trim()
  if (!trimmed) return ''
  const upper = trimmed.toUpperCase()
  if (upper.length === 2 && CODE_SET.has(upper)) return upper
  return LOWER_NAME_TO_CODE.get(trimmed.toLowerCase()) ?? ''
}
